"""
Train QRC readout on one local-simulator year, then adapt/evaluate on 2026.

No QPU jobs are submitted. The 2025 training features are generated locally.
The 2026 transition/evaluation features are generated by qBraid simulator API
by default, then saved before any readout adaptation. The default workflow is:
    1. download/build SPY data;
    2. fit HAR on rows before the train year;
    3. generate local-simulator QRC features for 2025;
    4. train a Ridge readout on 2025 simulator features;
    5. generate the first 100 feature rows from 2026 on qBraid simulator;
    6. use the first transition rows to adapt only the readout;
    7. evaluate on the remaining 2026 rows.
"""

